# Allow very large CSV fields
maximum_field_size = sys.maxsize

while True:
    try:
        csv.field_size_limit(maximum_field_size)
        break
    except OverflowError:
        maximum_field_size //= 10


def detect_encoding(file_path: Path):
    """
    Detect common CSV encodings and preserve the BOM when necessary.

    Returns:
        read_encoding
        write_encoding
        output_bom
    """
    with file_path.open("rb") as file:
        beginning = file.read(131072)

    if beginning.startswith(b"\xef\xbb\xbf"):
        return "utf-8-sig", "utf-8", b"\xef\xbb\xbf"

    if beginning.startswith(b"\xff\xfe"):
        return "utf-16", "utf-16-le", b"\xff\xfe"

    if beginning.startswith(b"\xfe\xff"):
        return "utf-16", "utf-16-be", b"\xfe\xff"

    try:
        beginning.decode("utf-8")
        return "utf-8", "utf-8", b""
    except UnicodeDecodeError:
        return "cp1252", "cp1252", b""


def detect_csv_dialect(file_path: Path, encoding: str):
    """
    Automatically detect the CSV delimiter and quoting format.
    Supports comma, semicolon, tab, and pipe delimiters.
    """
    with file_path.open(
        "r",
        encoding=encoding,
        newline="",
        errors="strict"
    ) as file:
        sample = file.read(131072)

    try:
        return csv.Sniffer().sniff(
            sample,
            delimiters=",;\t|"
        )
    except csv.Error:
        print(
            "CSV delimiter could not be detected automatically. "
            "Comma delimiter will be used."
        )
        return csv.excel


def split_csv_by_size(
    source_file: Path,
    maximum_size_bytes: int
):
    if not source_file.exists():
        raise FileNotFoundError(
            f"Source file does not exist:\n{source_file}"
        )

    if not source_file.is_file():
        raise ValueError(
            f"The supplied path is not a file:\n{source_file}"
        )

    output_folder = (
        source_file.parent
        / f"{source_file.stem}_split_250MB"
    )

    output_folder.mkdir(
        parents=True,
        exist_ok=True
    )

    # Remove old parts generated by this script
    for old_file in output_folder.glob(
        f"{source_file.stem}_part_*.csv"
    ):
        old_file.unlink()

    read_encoding, write_encoding, output_bom = detect_encoding(
        source_file
    )

    dialect = detect_csv_dialect(
        source_file,
        read_encoding
    )

    print("=" * 90)
    print("CSV SPLITTER")
    print("=" * 90)
    print(f"Source file:    {source_file}")
    print(f"Source size:    {source_file.stat().st_size:,} bytes")
    print(f"Maximum size:   {maximum_size_bytes:,} bytes")
    print(f"Encoding:       {read_encoding}")
    print(f"Delimiter:      {repr(dialect.delimiter)}")
    print(f"Output folder:  {output_folder}")
    print("=" * 90)

    part_number = 0
    total_rows = 0
    rows_in_current_part = 0
    current_file_size = 0
    current_output_file = None
    current_output_path = None

    # Reusable buffer used to convert one CSV row into bytes
    row_buffer = io.StringIO(newline="")
    row_writer = csv.writer(
        row_buffer,
        dialect=dialect
    )

    def convert_row_to_bytes(row):
        row_buffer.seek(0)
        row_buffer.truncate(0)

        row_writer.writerow(row)

        return row_buffer.getvalue().encode(
            write_encoding,
            errors="strict"
        )

    def open_new_part(header_bytes):
        nonlocal part_number
        nonlocal current_output_file
        nonlocal current_output_path
        nonlocal current_file_size
        nonlocal rows_in_current_part

        part_number += 1

        current_output_path = output_folder / (
            f"{source_file.stem}_part_{part_number:03d}.csv"
        )

        current_output_file = current_output_path.open("wb")

        if output_bom:
            current_output_file.write(output_bom)

        current_output_file.write(header_bytes)

        current_file_size = (
            len(output_bom)
            + len(header_bytes)
        )

        rows_in_current_part = 0

    try:
        with source_file.open(
            "r",
            encoding=read_encoding,
            newline="",
            errors="strict"
        ) as input_file:

            reader = csv.reader(
                input_file,
                dialect=dialect
            )

            try:
                header = next(reader)
            except StopIteration:
                raise ValueError(
                    "The source CSV file is empty."
                )

            header_bytes = convert_row_to_bytes(header)

            if len(output_bom) + len(header_bytes) > maximum_size_bytes:
                raise ValueError(
                    "The CSV header alone is larger than the "
                    "maximum output file size."
                )

            open_new_part(header_bytes)

            for row in reader:
                row_bytes = convert_row_to_bytes(row)

                projected_size = (
                    current_file_size
                    + len(row_bytes)
                )

                # Start a new part before writing the row
                if (
                    projected_size > maximum_size_bytes
                    and rows_in_current_part > 0
                ):
                    current_output_file.close()

                    print(
                        f"Created: {current_output_path.name} | "
                        f"Rows: {rows_in_current_part:,} | "
                        f"Size: {current_file_size:,} bytes"
                    )

                    open_new_part(header_bytes)

                row_with_header_size = (
                    len(output_bom)
                    + len(header_bytes)
                    + len(row_bytes)
                )

                if row_with_header_size > maximum_size_bytes:
                    print(
                        "\nWARNING: One CSV row is larger than "
                        "the maximum file size."
                    )
                    print(
                        "That row cannot be split without damaging "
                        "the CSV structure."
                    )

                current_output_file.write(row_bytes)

                current_file_size += len(row_bytes)
                rows_in_current_part += 1
                total_rows += 1

            if current_output_file is not None:
                current_output_file.close()
                current_output_file = None

                print(
                    f"Created: {current_output_path.name} | "
                    f"Rows: {rows_in_current_part:,} | "
                    f"Size: {current_file_size:,} bytes"
                )

    finally:
        if current_output_file is not None:
            current_output_file.close()

    print("=" * 90)
    print("SPLIT COMPLETED")
    print("=" * 90)
    print(f"Total data rows: {total_rows:,}")
    print(f"Files created:   {part_number:,}")
    print(f"Output folder:   {output_folder}")
    print("=" * 90)


